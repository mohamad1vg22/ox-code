export type IconName = keyof typeof ICONS | string

export function Icon({
  name,
  size = 14,
  strokeWidth = 1.75,
  style,
  className
}: {
  name: IconName
  size?: number
  strokeWidth?: number
  style?: CSSProperties
  className?: string
}): React.JSX.Element {
  const glyph = ICONS[name] ?? ICONS.circle
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={{ flexShrink: 0, verticalAlign: '-2px', ...style }}
      aria-hidden="true"
    >
      {glyph}
    </svg>
  )
}

/** Map a file extension to a monochrome file-type icon name. */
export function fileTypeIcon(name: string): IconName {
  const ext = name.split('.').pop()?.toLowerCase() ?? ''
  if (['ts', 'tsx', 'js', 'jsx', 'mjs', 'cjs'].includes(ext)) return 'file-code'
  if (ext === 'json') return 'braces'
  if (ext === 'md') return 'file-text'
  if (['css', 'scss', 'less'].includes(ext)) return 'brush'
  if (['html', 'htm', 'xml', 'svg'].includes(ext)) return 'globe'
  if (ext === 'py') return 'file-code'
  if (['png', 'jpg', 'jpeg', 'gif', 'webp', 'ico'].includes(ext)) return 'image'
  if (['yml', 'yaml', 'toml', 'ini', 'conf'].includes(ext)) return 'sliders'
  if (ext === 'lock') return 'lock'
  return 'file'
}
